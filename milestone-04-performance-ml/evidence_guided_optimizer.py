"""Small OPTIMAS-inspired experiment: profiler evidence + ML + verified A/B tuning.

Run from milestone-04-performance-ml with the locally generated reports and MLP:
    python3 evidence_guided_optimizer.py

This is a fixed, controlled A -> B proposal, not an autonomous code editor.
"""

import csv
import json
import random
import re
import subprocess
from datetime import datetime
from pathlib import Path
from statistics import median

import numpy as np
import torch
from torch import nn
import triton
import triton.testing

from triton_matmul import matmul_kernel

BASE = Path(__file__).resolve().parent
RESULTS = BASE / "results"
RESULTS.mkdir(exist_ok=True)

M, N, K = 512, 1024, 256
CONFIGS = {
    "A": (32, 64, 32, 4),
    "B": (64, 64, 32, 4),
}
SEEDS = [42, 43, 44]
TIMING_TRIALS = 5
REPETITION_MS = 100
MIN_SPEEDUP = 1.02           # Practical threshold, not a significance test
MIN_FASTER_TRIALS = 4        # Out of 5 paired measurement rounds

FEATURES = [
    "M", "N", "K", "block_m", "block_n", "block_k", "num_warps"
]


# 1. Read already-collected NVIDIA profiler reports.
def extract_metric(report_text, name):
    pattern = re.compile(
        r"^\s*" + re.escape(name) +
        r"\s+(?:\S+\s+)?([-+]?\d+(?:\.\d+)?)\s*$"
    )
    for line in report_text.splitlines():
        match = pattern.match(line)
        if match:
            return float(match.group(1))
    raise ValueError(f"Missing Nsight metric: {name}")


def read_profile(name):
    path = RESULTS / f"profile_{name}.ncu-repz"
    if not path.is_file():
        raise FileNotFoundError(f"Profiler report not found: {path}")

    proc = subprocess.run(
        ["ncu", "--import", str(path), "--page", "details"],
        text=True, capture_output=True, check=True,
    )
    (RESULTS / f"profile_{name}_details.txt").write_text(proc.stdout)

    labels = {
        "duration_us": "Duration",
        "grid_blocks": "Grid Size",
        "registers_per_thread": "Registers Per Thread",
        "shared_memory_kb_per_block": "Dynamic Shared Memory Per Block",
        "achieved_occupancy_percent": "Achieved Occupancy",
        "theoretical_occupancy_percent": "Theoretical Occupancy",
        "compute_throughput_percent": "Compute (SM) Throughput",
        "dram_throughput_percent": "DRAM Throughput",
        "l2_throughput_percent": "L2 Cache Throughput",
    }
    return {key: extract_metric(proc.stdout, label)
            for key, label in labels.items()}


# 2. Load the existing, FROZEN 7-input MLP (no retraining).
class AutotunerMLP(nn.Module):
    def __init__(self):
        super().__init__()
        self.network = nn.Sequential(
            nn.Linear(7, 32), nn.ReLU(),
            nn.Linear(32, 16), nn.ReLU(),
            nn.Linear(16, 1),
        )

    def forward(self, x):
        return self.network(x)


def predict_latency_ms():
    checkpoint_path = RESULTS / "mlp_autotuner.pt"
    # Load only the checkpoint generated by your own train_autotuner_mlp.py.
    checkpoint = torch.load(
        checkpoint_path, map_location="cpu", weights_only=True
    )
    if checkpoint["features"] != FEATURES:
        raise ValueError("MLP feature schema does not match this experiment")

    model = AutotunerMLP()
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()
    mean = np.asarray(checkpoint["scaler_mean"], dtype=np.float64)
    scale = np.asarray(checkpoint["scaler_scale"], dtype=np.float64)

    predictions = {}
    for name, (bm, bn, bk, warps) in CONFIGS.items():
        x = np.array([M, N, K, bm, bn, bk, warps], dtype=np.float64)
        x = ((np.log2(x) - mean) / scale).astype(np.float32)
        with torch.no_grad():
            predictions[name] = float(
                torch.exp(model(torch.from_numpy(x[None, :]))).item()
            )
    return predictions


# 3. Launch the same Triton kernel with either configuration.
def launch(name, A, B, C):
    bm, bn, bk, warps = CONFIGS[name]
    grid = (triton.cdiv(M, bm), triton.cdiv(N, bn))
    matmul_kernel[grid](
        A, B, C, M, N, K, bm, bn, bk, num_warps=warps
    )


# 4. Check correctness using several independently generated inputs.
def validate_correctness():
    errors = {"A": [], "B": []}
    for seed in SEEDS:
        torch.manual_seed(seed)
        A = torch.rand((M, K), device="cuda", dtype=torch.float16) - 0.5
        B = torch.rand((K, N), device="cuda", dtype=torch.float16) - 0.5
        ref = torch.mm(A, B)
        outputs = {
            name: torch.empty((M, N), device="cuda", dtype=torch.float16)
            for name in CONFIGS
        }
        for name, C in outputs.items():
            launch(name, A, B, C)
            torch.cuda.synchronize()
            torch.testing.assert_close(C, ref, atol=0.02, rtol=0.01)
            errors[name].append(float((C.float() - ref.float()).abs().max()))
    return errors


# 5. Fresh, paired A/B CUDA Graph timings (not Nsight duration).
def benchmark_pairs():
    torch.manual_seed(2026)
    A = torch.rand((M, K), device="cuda", dtype=torch.float16) - 0.5
    B = torch.rand((K, N), device="cuda", dtype=torch.float16) - 0.5
    outputs = {
        name: torch.empty((M, N), device="cuda", dtype=torch.float16)
        for name in CONFIGS
    }
    for name in CONFIGS:
        launch(name, A, B, outputs[name])   # Compile outside timing
    torch.cuda.synchronize()

    rounds = []
    rng = random.Random(42)
    for trial in range(1, TIMING_TRIALS + 1):
        order = list(CONFIGS)
        rng.shuffle(order)                # Reduce systematic order effects
        times = {}
        for name in order:
            C = outputs[name]
            times[name] = float(triton.testing.do_bench_cudagraph(
                lambda name=name, C=C: launch(name, A, B, C),
                rep=REPETITION_MS,
                return_mode="median",
            ))
        rounds.append({"trial": trial, "A_ms": times["A"],
                       "B_ms": times["B"], "measurement_order": "-".join(order)})
    return rounds


def main():
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA GPU required")

    print("=== 1. Existing Nsight Compute evidence ===")
    profiles = {name: read_profile(name) for name in CONFIGS}
    for name, p in profiles.items():
        print(f"{name}: grid={p['grid_blocks']:.0f}, "
              f"occupancy={p['achieved_occupancy_percent']:.2f}%, "
              f"registers/thread={p['registers_per_thread']:.0f}, "
              f"shared_memory={p['shared_memory_kb_per_block']:.2f} KB")

    print("\n=== 2. Frozen MLP predictions ===")
    predictions = predict_latency_ms()
    for name, latency in predictions.items():
        print(f"{name}: {latency * 1000:.3f} us predicted")
    mlp_choice = min(predictions, key=predictions.get)
    print("MLP preference:", mlp_choice)

    # Controlled proposal: change ONLY BLOCK_M from 32 to 64.
    # The larger tile may improve data reuse or reduce tile scheduling work,
    # but B also has fewer blocks and lower occupancy. These are hypotheses,
    # NOT proven causes of a speed difference.
    hypothesis = (
        "Test increasing BLOCK_M from 32 to 64 while holding BLOCK_N, "
        "BLOCK_K, and num_warps fixed. The larger tile may improve work "
        "efficiency, but it also reduces grid size and occupancy."
    )
    print("\n=== 3. Proposed A -> B experiment ===")
    print(hypothesis)

    print("\n=== 4. Correctness verification ===")
    errors = validate_correctness()  # Raises and stops on any failure
    print("Both configurations passed all three input seeds.")

    print("\n=== 5. Fresh CUDA Graph timings ===")
    rounds = benchmark_pairs()
    for row in rounds:
        print(f"Trial {row['trial']}: A={row['A_ms'] * 1000:.3f} us, "
              f"B={row['B_ms'] * 1000:.3f} us ({row['measurement_order']})")

    A_med = median(x["A_ms"] for x in rounds)
    B_med = median(x["B_ms"] for x in rounds)
    faster_rounds = sum(x["B_ms"] < x["A_ms"] for x in rounds)
    speedup = A_med / B_med
    accept_B = speedup >= MIN_SPEEDUP and faster_rounds >= MIN_FASTER_TRIALS

    decision = "ACCEPT_B" if accept_B else "KEEP_A"
    print(f"\nMedian A={A_med * 1000:.3f} us; B={B_med * 1000:.3f} us")
    print(f"B speedup vs A: {speedup:.3f}x; B faster in {faster_rounds}/5 rounds")
    print("Provisional decision:", decision)

    report = {
        "timestamp_local": datetime.now().astimezone().isoformat(),
        "workload": {"M": M, "N": N, "K": K, "dtype": "float16"},
        "environment": {
            "gpu": torch.cuda.get_device_name(0),
            "pytorch": torch.__version__,
            "triton": triton.__version__,
            "cuda_build": torch.version.cuda,
            "benchmark": "triton.testing.do_bench_cudagraph",
            "repetition_budget_ms": REPETITION_MS,
            "timing_trials": TIMING_TRIALS,
        },
        "configurations": {k: list(v) for k, v in CONFIGS.items()},
        "profile_metrics": profiles,
        "mlp_predicted_latency_ms": predictions,
        "mlp_preferred_configuration": mlp_choice,
        "proposal": {"baseline": "A", "candidate": "B", "hypothesis": hypothesis},
        "correctness": {"passed": True, "max_abs_error_by_seed": errors,
                        "atol": 0.02, "rtol": 0.01},
        "timing_rounds": rounds,
        "measured_median_latency_ms": {"A": A_med, "B": B_med},
        "speedup_B_over_A": speedup,
        "B_faster_rounds": faster_rounds,
        "decision": decision,
        "decision_rule": ("Accept B only when median speedup >= 1.02x "
                          "and B is faster in >= 4/5 timing rounds"),
        "limitations": [
            "One workload, two preselected configurations, one GPU; not a general optimizer.",
            "Profiler counters characterize resource usage but do not prove why B is faster.",
            "Nsight instrumented duration is not compared with CUDA Graph timing.",
            "Acceptance thresholds are practical heuristics, not statistical significance tests.",
            "MLP is frozen; this run does not retrain it or change the held-out test results.",
            "This is a controlled fixed-candidate study, not automatic LLM code editing.",
        ],
    }

    out_json = RESULTS / "evidence_guided_report.json"
    out_json.write_text(json.dumps(report, indent=2, default=str) + "\n")
    out_csv = RESULTS / "evidence_guided_timings.csv"
    with out_csv.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rounds[0]))
        writer.writeheader()
        writer.writerows(rounds)

    print("\nSaved:", out_json)
    print("Saved:", out_csv)
    print("This is an evidence-guided prototype, not a full OPTIMAS reproduction.")


if __name__ == "__main__":
    main()
